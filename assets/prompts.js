export const MODE_LABEL = { abstract: '抄録', slides: '発表スライド' };

export function rubricText(items) {
  return items.map((r, i) =>
    `${i + 1}. ${r.name}（${r.max}点）\n   高得点の目安：${r.high}\n   低得点の目安：${r.low}`
  ).join('\n');
}

export function scoresTemplate(items) {
  return items.map(r => `${r.name}: 点/${r.max}`).join('\n');
}

